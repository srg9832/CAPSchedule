create or replace function public.uniform_upsert_cadet(
  p_capid text,p_first_name text,p_last_name text,p_grade text,p_unit_id uuid
)
returns table (id uuid,capid text,first_name text,last_name text,name text,grade text,current_unit_id uuid)
language plpgsql security definer set search_path = pg_catalog
as $$
declare
  v_member_id uuid;
  v_current_unit uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required.'; end if;
  if p_unit_id is null or not public.has_uniform_unit_access(p_unit_id) then
    raise exception 'You do not have Uniform Inspection access to this unit.';
  end if;
  if nullif(trim(p_capid),'') is null then raise exception 'CAPID is required.'; end if;

  insert into public.members(capid,first_name,last_name,member_type,active,current_grade,created_at,updated_at)
  values(trim(p_capid),trim(coalesce(p_first_name,'')),trim(coalesce(p_last_name,'')),'Cadet',true,nullif(trim(coalesce(p_grade,'')),''),now(),now())
  on conflict(capid) do update set
    first_name=excluded.first_name,last_name=excluded.last_name,
    current_grade=coalesce(excluded.current_grade,public.members.current_grade),
    active=true,updated_at=now()
  returning public.members.id into v_member_id;

  select a.unit_id into v_current_unit
  from public.member_unit_assignments a
  where a.member_id=v_member_id and a.active and a.is_primary
  limit 1;

  if v_current_unit is null then
    insert into public.member_unit_assignments(member_id,unit_id,is_primary,active,start_date)
    values(v_member_id,p_unit_id,true,true,current_date);
  elsif v_current_unit <> p_unit_id and public.is_uniform_app_admin() then
    update public.member_unit_assignments
      set active=false,is_primary=false,end_date=coalesce(end_date,current_date),updated_at=now()
    where member_id=v_member_id and active and is_primary;
    insert into public.member_unit_assignments(member_id,unit_id,is_primary,active,start_date)
    values(v_member_id,p_unit_id,true,true,current_date);
  end if;

  return query select c.id,c.capid,c.first_name,c.last_name,c.name,c.grade,c.current_unit_id
  from public.uniform_cadets c where c.id=v_member_id;
end;
$$;

create or replace function public.uniform_save_inspection(p_payload jsonb)
returns jsonb
language plpgsql security definer set search_path = pg_catalog
as $$
declare
  v_uid uuid := auth.uid();
  v_unit uuid;
  v_member record;
  v_inspection public.uniform_inspections%rowtype;
  v_evaluator_name text;
  v_client_uuid uuid;
begin
  if v_uid is null then raise exception 'Authentication required.'; end if;
  v_unit := nullif(p_payload->>'unit_id','')::uuid;
  if v_unit is null or not public.has_uniform_unit_access(v_unit) then
    raise exception 'You do not have Uniform Inspection access to this unit.';
  end if;

  select * into v_member
  from public.uniform_upsert_cadet(
    p_payload->>'capid',p_payload->>'first_name',p_payload->>'last_name',
    p_payload->>'grade',v_unit
  ) limit 1;

  select coalesce(p.display_name,u.email)::text into v_evaluator_name
  from auth.users u left join public.profiles p on p.id=u.id where u.id=v_uid;
  v_client_uuid := nullif(p_payload->>'client_uuid','')::uuid;

  insert into public.uniform_inspections(
    member_id,unit_id,inspection_date,grade_at_inspection,grade_group,
    personal_appearance,garments,accoutrements,footwear,military_bearing,
    total_score,overall_rating,passed,notes,evaluator_user_id,evaluator_name,client_uuid
  ) values (
    v_member.id,v_unit,coalesce(nullif(p_payload->>'inspection_date','')::date,current_date),
    coalesce(nullif(p_payload->>'grade_at_inspection',''),v_member.grade,''),
    p_payload->>'grade_group',
    (p_payload->>'personal_appearance')::smallint,(p_payload->>'garments')::smallint,
    (p_payload->>'accoutrements')::smallint,(p_payload->>'footwear')::smallint,
    (p_payload->>'military_bearing')::smallint,
    0,'Needs Improvement',false,nullif(p_payload->>'notes',''),
    v_uid,coalesce(v_evaluator_name,'Unknown Inspector'),v_client_uuid
  )
  on conflict(client_uuid) do update set
    member_id=excluded.member_id,unit_id=excluded.unit_id,inspection_date=excluded.inspection_date,
    grade_at_inspection=excluded.grade_at_inspection,grade_group=excluded.grade_group,
    personal_appearance=excluded.personal_appearance,garments=excluded.garments,
    accoutrements=excluded.accoutrements,footwear=excluded.footwear,
    military_bearing=excluded.military_bearing,notes=excluded.notes,
    evaluator_user_id=excluded.evaluator_user_id,evaluator_name=excluded.evaluator_name
  returning * into v_inspection;

  return jsonb_build_object(
    'inspection',
    to_jsonb(v_inspection) || jsonb_build_object(
      'cadets',jsonb_build_object(
        'id',v_member.id,'capid',v_member.capid,'first_name',v_member.first_name,
        'last_name',v_member.last_name,'name',v_member.name,'grade',v_member.grade,
        'current_unit_id',v_member.current_unit_id
      ),
      'units',(select to_jsonb(u) from (select id,charter_number,name,active from public.units where id=v_unit) u)
    ),
    'cadet',to_jsonb(v_member)
  );
end;
$$;

