create or replace view public.uniform_cadets
with (security_invoker = true)
as
select
  m.id,
  m.capid,
  m.first_name,
  m.last_name,
  trim(concat_ws(' ',m.first_name,m.last_name)) as name,
  m.current_grade as grade,
  (
    select a.unit_id
    from public.member_unit_assignments a
    where a.member_id = m.id and a.active and a.is_primary
    order by a.start_date desc, a.created_at desc
    limit 1
  ) as current_unit_id
from public.members m
where m.member_type = 'Cadet' and m.active;

