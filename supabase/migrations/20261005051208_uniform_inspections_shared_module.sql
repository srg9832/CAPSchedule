create or replace function public.uniform_calculate_inspection_result()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
declare
  score_total smallint;
  pass_min smallint;
  excellent_minimum smallint;
begin
  score_total := new.personal_appearance + new.garments + new.accoutrements + new.footwear + new.military_bearing;
  new.total_score := score_total;

  select r.passing_min, r.excellent_min
    into pass_min, excellent_minimum
  from public.uniform_grading_rules r
  where r.grade_group = new.grade_group;

  if pass_min is null or excellent_minimum is null then
    if new.grade_group = 'airman' then
      pass_min := 4;
      excellent_minimum := 6;
    else
      pass_min := 5;
      excellent_minimum := 8;
    end if;
  end if;

  if score_total < pass_min then
    new.overall_rating := 'Needs Improvement';
    new.passed := false;
  elsif score_total < excellent_minimum then
    new.overall_rating := 'Satisfactory';
    new.passed := true;
  else
    new.overall_rating := 'Excellent';
    new.passed := true;
  end if;
  return new;
end;
$$;

